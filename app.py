@app.post("/detect")
async def detect(
    bbox: Optional[str] = Form(None),
    project_point: Optional[str] = Form(None),
    buffers: Optional[str] = Form(None),
    enable_ndwi: Optional[bool] = Form(False),
    ndwi_start: Optional[str] = Form(None),
    ndwi_end: Optional[str] = Form(None),
    ec_pdf: Optional[UploadFile] = File(None),
    project_geojson: Optional[UploadFile] = File(None),
):
    """Run detection. Either upload project_geojson or provide project_point.

    If bbox is omitted, it is inferred from the project geometry or project_point.
    Returns JSON with report and links to outputs.
    """
    proj_point_tuple = None
    if project_point:
        try:
            lon, lat = [float(x) for x in project_point.split(",")]
            proj_point_tuple = (lon, lat)
        except Exception:
            return JSONResponse(status_code=400, content={"error": "project_point must be lon,lat"})

    project_geojson_path = None
    if project_geojson:
        contents = await project_geojson.read()
        project_geojson_path = os.path.join("outputs", next(tempfile._get_candidate_names()), project_geojson.filename or "project.geojson")
        os.makedirs(os.path.dirname(project_geojson_path), exist_ok=True)
        with open(project_geojson_path, "wb") as f:
            f.write(contents)

    if bbox:
        try:
            bbox_vals = tuple(float(x) for x in bbox.split(","))
        except Exception:
            return JSONResponse(status_code=400, content={"error": "bbox must be minlon,minlat,maxlon,maxlat"})
    else:
        if project_geojson_path:
            try:
                with open(project_geojson_path, "r", encoding="utf-8") as f:
                    payload = json.load(f)
                derived = _bbox_from_geojson_payload(payload)
                if derived is None:
                    raise ValueError("No coordinates found in GeoJSON")
                bbox_vals = derived
            except Exception:
                if proj_point_tuple is None:
                    return JSONResponse(status_code=400, content={"error": "bbox is required when project file has no coordinates or when no project point is given"})
                bbox_vals = _bbox_from_point(*proj_point_tuple)
        elif proj_point_tuple is not None:
            bbox_vals = _bbox_from_point(*proj_point_tuple)
        else:
            return JSONResponse(status_code=400, content={"error": "bbox is required unless project_point or project_geojson is provided"})

    buffer_list = [30.0, 50.0, 100.0]
    if buffers:
        try:
            buffer_list = [float(x) for x in buffers.split(",")]
        except Exception:
            return JSONResponse(status_code=400, content={"error": "buffers must be comma-separated numbers"})

    if isinstance(enable_ndwi, str):
        enable_ndwi_flag = enable_ndwi.lower() in ("1", "true", "yes", "on")
    else:
        enable_ndwi_flag = bool(enable_ndwi)

    out_dir = os.path.join("outputs", next(tempfile._get_candidate_names()))
    os.makedirs(out_dir, exist_ok=True)

    if project_geojson and project_geojson_path and os.path.exists(project_geojson_path):
        # move uploaded project geojson into the run output directory for traceability
        target_path = os.path.join(out_dir, project_geojson.filename or "project.geojson")
        if project_geojson_path != target_path:
            with open(project_geojson_path, "rb") as src, open(target_path, "wb") as dst:
                dst.write(src.read())
            project_geojson_path = target_path

    # If an EC PDF is provided, try to parse buffer distances from it
    parsed_buffers = None
    ec_parse_path = None
    if ec_pdf:
        from ec_parser import parse_ec_pdf
        contents = await ec_pdf.read()
        pdf_path = os.path.join(out_dir, ec_pdf.filename or "ec.pdf")
        with open(pdf_path, "wb") as f:
            f.write(contents)
        try:
            parsed = parse_ec_pdf(pdf_path)
            parsed_buffers = parsed.get('buffers_m', [])
        except Exception as e:
            parsed = {'buffers_m': [], 'llm_used': False, 'llm_error': str(e), 'raw_text': ''}
            parsed_buffers = []
        try:
            ec_parse_path = os.path.join(out_dir, 'ec_parse.json')
            with open(ec_parse_path, 'w', encoding='utf-8') as pf:
                json.dump(parsed, pf, indent=2)
        except Exception:
            ec_parse_path = None

    if parsed_buffers and len(parsed_buffers) > 0 and not buffers:
        buffer_list = parsed_buffers

    try:
        result = run_detection(
            bbox_vals,
            project_geojson_path=project_geojson_path,
            project_point=proj_point_tuple,
            buffers=buffer_list,
            out_dir=out_dir,
            enable_ndwi=enable_ndwi_flag,
            ndwi_dates=(ndwi_start, ndwi_end),
        )
    except Exception as e:
        return JSONResponse(status_code=500, content={"error": str(e)})

    report_pdf_path = os.path.join(out_dir, "report.pdf")
    try:
        _write_report_pdf(result["report"], report_pdf_path, os.path.basename(out_dir))
    except Exception:
        report_pdf_path = None

    ec_parse_url = None
    if ec_parse_path:
        ec_parse_url = f"/outputs/{os.path.basename(out_dir)}/ec_parse.json"

    base_url = f"/outputs/{os.path.basename(out_dir)}"
    response = {
        "run_id": os.path.basename(out_dir),
        "report": result["report"],
        "report_url": base_url + "/report.json",
        "report_pdf_url": base_url + "/report.pdf" if report_pdf_path else None,
        "evidence_url": base_url + "/evidence.geojson",
        "map_url": base_url + "/map.png",
    }
    if result.get("ndwi_path"):
        response["ndwi_url"] = base_url + "/ndwi.png"
    if result.get("ndwi_error"):
        response["ndwi_error"] = result.get("ndwi_error")
    if ec_parse_url:
        response["ec_parse_url"] = ec_parse_url

    return JSONResponse(status_code=200, content=response)


