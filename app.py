def _write_report_pdf(report, output_path, run_id):
    """Write a readable PDF summary for a completed detection run."""
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="SmallMuted", parent=styles["Normal"], fontSize=8.5, textColor=colors.HexColor("#64748b"), leading=12))
    styles.add(ParagraphStyle(name="Section", parent=styles["Heading2"], fontSize=13, textColor=colors.HexColor("#164e63"), spaceBefore=12, spaceAfter=7))
    styles["Title"].textColor = colors.HexColor("#0f3d3e")
    styles["Title"].fontSize = 23

    def safe(value):
        return escape(str(value if value is not None else ""))

    summary = report.get("summary", {})
    quality = report.get("data_quality", {})
    violations = report.get("violations", [])
    findings = report.get("findings", [])
    issues = report.get("issues", [])
    doc = SimpleDocTemplate(output_path, pagesize=A4, rightMargin=16 * mm, leftMargin=16 * mm, topMargin=15 * mm, bottomMargin=15 * mm)
    story = [Paragraph("Waterbody Buffer Detection", styles["Title"]), Paragraph(f"Analysis report | Run {safe(run_id)}", styles["SmallMuted"]), Spacer(1, 10)]
    story.append(Paragraph("Executive summary", styles["Section"]))
    summary_rows = [["Status", safe(summary.get("status", "unknown"))], ["Confidence", safe(summary.get("confidence", "unknown"))], ["Violations found", safe(summary.get("violations_found", len(violations)))], ["Water source", safe(quality.get("water_source", "unknown"))], ["Water features", safe(quality.get("water_feature_count", "unknown"))]]
    table = Table(summary_rows, colWidths=[48 * mm, 120 * mm])
    table.setStyle(TableStyle([("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#e8f4ee")), ("GRID", (0, 0), (-1, -1), .35, colors.HexColor("#cbded3")), ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"), ("VALIGN", (0, 0), (-1, -1), "TOP"), ("PADDING", (0, 0), (-1, -1), 7)]))
    story.append(table)
    story.append(Paragraph("Buffer checks", styles["Section"]))
    rows = [["Buffer", "Intersects", "Intersections"]]
    rows.extend([[f"{item.get('buffer_m', '')} m", "Yes" if item.get("intersects") else "No", str(item.get("num_intersections", 0))] for item in violations])
    if len(rows) == 1:
        rows.append(["-", "No violations recorded", "-"])
    checks = Table(rows, colWidths=[45 * mm, 55 * mm, 55 * mm], repeatRows=1)
    checks.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#164e63")), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("GRID", (0, 0), (-1, -1), .35, colors.HexColor("#cbd5e1")), ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f5faf7")]), ("PADDING", (0, 0), (-1, -1), 7)]))
    story.append(checks)
    if findings or issues:
        story.append(Paragraph("Findings and notes", styles["Section"]))
        for item in findings:
            story.append(Paragraph(f"<b>{safe(item.get('risk', 'note')).upper()}</b> - {safe(item.get('message', ''))}", styles["Normal"]))
        for issue in issues:
            story.append(Paragraph(f"- {safe(issue)}", styles["Normal"]))
    story.append(Spacer(1, 12))
    story.append(Paragraph("Generated by the Waterbody Buffer Detection dashboard. Use the evidence GeoJSON and map artifact for spatial verification.", styles["SmallMuted"]))
    doc.build(story)


