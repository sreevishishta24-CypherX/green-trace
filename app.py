@app.get("/runs")
async def list_runs():
    runs = []
    if os.path.isdir("outputs"):
        for entry in sorted(os.listdir("outputs"), reverse=True):
            path = os.path.join("outputs", entry)
            if not os.path.isdir(path):
                continue
            report_path = os.path.join(path, "report.json")
            report_pdf_path = os.path.join(path, "report.pdf")
            evidence_path = os.path.join(path, "evidence.geojson")
            map_path = os.path.join(path, "map.png")
            runs.append({
                "id": entry,
                "report_url": f"/outputs/{entry}/report.json" if os.path.exists(report_path) else None,
                "report_pdf_url": f"/outputs/{entry}/report.pdf" if os.path.exists(report_pdf_path) else None,
                "evidence_url": f"/outputs/{entry}/evidence.geojson" if os.path.exists(evidence_path) else None,
                "map_url": f"/outputs/{entry}/map.png" if os.path.exists(map_path) else None,
            })
    return {"runs": runs[:10]}


def _bbox_from_geojson_payload(payload):
    """Return bbox from a GeoJSON object as (minlon, minlat, maxlon, maxlat)."""
    xs = []
    ys = []

    def walk(obj):
        if isinstance(obj, dict):
            if "coordinates" in obj:
                walk(obj["coordinates"])
            if "geometry" in obj and obj["geometry"] is not None:
                walk(obj["geometry"])
            if "features" in obj:
                for item in obj["features"]:
                    walk(item)
            if "feature" in obj:
                walk(obj["feature"])
        elif isinstance(obj, list):
            if obj and all(isinstance(v, (int, float)) for v in obj[:2]):
                if len(obj) >= 2:
                    xs.append(float(obj[0]))
                    ys.append(float(obj[1]))
            else:
                for item in obj:
                    walk(item)

    walk(payload)
    if not xs or not ys:
        return None

    buffer_pad = max(0.01, (max(xs) - min(xs)) * 0.15, (max(ys) - min(ys)) * 0.15)
    return (min(xs) - buffer_pad, min(ys) - buffer_pad, max(xs) + buffer_pad, max(ys) + buffer_pad)


def _bbox_from_point(lon: float, lat: float, pad_deg: float = 0.01):
    return (lon - pad_deg, lat - pad_deg, lon + pad_deg, lat + pad_deg)


